def flash_viralmedia(st: GameState, data: GameData, mode: str, num: int = 0, genre: int = 0) -> str:
    """`@FLASH_VIRALMEDIA(mode,num,genre)`:754–882（#FUNCTIONS：RESULT を書かない）。"""
    if mode in _VIRAL_LINES:
        c = _chara(st, num)
        head = ("人気" if _exp(data, c, "魅了経験") >= 200 else "新人") + mode + "の"  # :766／:812
        tc = _chara(st, st.target)  # :769／:815 は num ではなく TARGET の素質を見る（原作どおり）
        suffix = "さん" if any(talent(data, tc, n) for n in _TSUYOKI) else "ちゃん"
        s2 = s3 = f"{head}{c.name}{suffix}"  # :775／:777（LOCALS:2 と LOCALS:3 は同じ式）
        lines = _VIRAL_LINES[mode]
        return _strdata(st, lines.get(genre, lines[None]), s2=s2, s3=s3)
    if mode == "通常":
        return _strdata(st, 858)
    raise NotImplementedError(f"FLASH_VIRALMEDIA の mode {mode!r}（呼出元に無い）")


