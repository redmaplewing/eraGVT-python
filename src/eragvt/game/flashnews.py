def flashnews_chooseheroine(st: GameState, data: GameData, mode: str) -> tuple[int, int]:
    """`@FLASHNEWS_CHOOSEHEROINE(mode)`:888–923：`RETURN LOCAL:1, LOCAL`（RESULT:0 = キャラ番号、RESULT:1 = 変身後フラグ）。

    :915–919 の LOCALS（`LOCAL:1==1` ならば NAME:(LOCAL)、それ以外は PRINT_TRANSNAME(TARGET)）は使われない（表示も代入先も無い）。
    """
    clear_randchoose(st)
    for i, c in enumerate(st.charas):
        if c.cflag[0] != 0:
            ts = talent(data, c, "変身時ＴＳ")
            if is_female(data, c):
                if mode != "変身後":
                    add_randchoose(st, i * 10)
                if mode != "変身前" and ts == 0:
                    add_randchoose(st, i * 10 + 1)
            elif mode != "変身前" and ts == 1:
                add_randchoose(st, i * 10 + 1)
    if choicecount(st) > 0:
        local = randchoose_f(st)
        no, flag = div(local, 10), mod(local, 10)
        _chara(st, flag if no == 1 else st.target)  # :916 NAME:(LOCAL)〔LOCAL は剰余後の 0／1〕／:918 の添字（範囲外なら原作でもエラー）
        st.result[0], st.result[1] = no, flag
        return no, flag
    st.result[0], st.result[1] = 0, 0
    return 0, 0


