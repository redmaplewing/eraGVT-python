def _priority_news(st: GameState, data: GameData, f60: int) -> str:
    """:69–166 `SELECTCASE FLAG:60`。"""
    from .raid import event_battle_flashnews

    if 100000 <= f60 <= 109999:  # :73–75 ミッション失敗
        event_battle_flashnews(st, f60 - 100000, 0)
        # 呼出先が RESULTS:0 を書かない場合（到達するのは 3004 の 0〔時間切れ＋被害〕と 5 の -1〔敗北〕）は前回の RESULTS:0
        # （`LOCALS'=RESULTS`）。戰後の BEGIN SHOP では @EVENTSHOP の後のオートセーブで @SAVEINFO が必ず走り（shop.save_info が
        # 同期）、@SHOW_SHOP:1–40／本関数 :1–74 には書き込みが無いので、通常は版数の "408"、讀檔直後は ""（S26b、result.md）。
        return st.results[0]
    if 110000 <= f60 <= 119999:  # :77–79 ミッション成功
        event_battle_flashnews(st, f60 - 110000, 1)
        return st.results[0]
    if 120000 <= f60 <= 129999:  # :81–88 ミッション以前に敗北幽閉
        event_battle_flashnews(st, f60 - 120000, -1)
        s = st.results[0]
        if s == "":
            event_battle_flashnews(st, f60 - 120000, 0)
            s = st.results[0]
        return s
    if f60 == 10001:  # :91–154 ゲームオーバーモード
        local = st.day[0] * 2 + st.time - st.day[2]  # :93 全滅からのターン数
        if st.flag[11] != 7:  # :152–153
            return _TEXT[153]
        if 1 <= local <= 9:  # :99–117
            return _TEXT[99 + 2 * local]
        tmp = st.temp
        if tmp.flashnews_viral >= 0:  # :119–121
            s = flash_viralmedia(st, data, "通常")
            tmp.flashnews_viral = 1
            return s
        no, trans = flashnews_chooseheroine(st, data, "通常")  # :124
        if no <= 0:
            return _TEXT[148]
        c = _chara(st, no)
        if trans == 1:  # :126–130
            s = print_transcallname(st, no)
            if s == c.callname:
                s = c.name
        else:
            s = c.name  # :132 %NAME:RESULT%
        s = _strdata(st, 134, s=s)
        return _strdata(st, 142, s=s)
    if f60 == 10000:  # :157–165 裏ボス戦闘中
        line = {1: 160, 2: 162, 3: 164}.get(st.flag[21])
        return _TEXT[line] if line is not None else ""
    return ""


def _random_news(st: GameState, data: GameData, hikan: int, sentou: int, chian: int) -> str:
    """:526–728（$NEWSLOOP の 1 回分）。"""
    local = st.rng.rand(100)
    if local < 8:  # :529–547 AV 出演作品・写真集（SAVESTR:21〜25）
        clear_randchoose(st)
        for k in range(21, 26):
            if st.savestr[k] != "":
                add_randchoose(st, k)
        if choicecount(st) > 0:
            st.result[1] = randchoose_f(st)
            return _strdata(st, 541, v=st.savestr[st.result[1]])
        return ""
    if local < 18:  # :550–654 魔法少女の活躍／被姦経験
        if hikan > 300:
            return _strdata(st, 553)
        if hikan > 60:
            return _strdata(st, 567)
        clear_randchoose(st)
        if hikan > 40:
            add_randchoose(st, 1)
        elif hikan > 30:
            add_randchoose(st, 2)
        elif hikan > 20 and hikan < 41:
            add_randchoose(st, 3)
        elif hikan > 10 and hikan < 21:
            add_randchoose(st, 4)
        elif sentou > 5 and hikan < 21:
            add_randchoose(st, 5)
        elif sentou and hikan < 41:
            add_randchoose(st, 6)
        elif sentou > 10 and hikan < 11:
            add_randchoose(st, 7)
        elif sentou:
            add_randchoose(st, 99)
        if choicecount(st) > 0:
            r = st.result[1] = randchoose_f(st)
            if r == 1:
                return _TEXT[611]
            if r in _CHOICE_STRDATA:
                return _strdata(st, _CHOICE_STRDATA[r])
            if r == 5:
                return _TEXT[635]
            if r == 99:
                return _TEXT[651]
        return ""
    if local < 26 and chian >= 5000:  # :657 人類側優勢
        return _strdata(st, 658)
    return _strdata(st, 669, item=data.names["ITEM"].get(399, ""))  # :668 コモンニュース


