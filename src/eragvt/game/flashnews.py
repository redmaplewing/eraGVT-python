def _strdata(st: GameState, line: int, **kw: str) -> str:
    """`STRDATA LOCALS … ENDDATA`（開始行 `line`）：RAND で 1 行選び、その行だけ評価する。"""
    items = _STRDATA[line]
    _, tmpl = items[st.rng.rand(len(items))]
    if "{x}" in tmpl:
        # :423 `%CONFIG_CHECK_MANIAC_F(14) && RAND:4 ? "…" # "…"%`（RAND:4 は MANIAC(14) が真のときだけ）
        hit = config_check_maniac(st, 14) != 0 and st.rng.rand(4) != 0
        kw["x"] = "四肢切断され肉壁と一体化" if hit else "子宮に触手幼体が多数寄生"
    return tmpl.format(**kw)


def _exp(data: GameData, c, name: str) -> int:
    return c.exp[data.index_of("EXP", name)]


def _chara(st: GameState, i: int):
    """`NAME:i` 等の添字（範囲外は原作でもエラー）。"""
    if not 0 <= i < st.charanum:
        raise NotImplementedError(f"キャラ番号 {i} が範囲外（原作でもエラー）")
    return st.charas[i]


