def _chain(rand, table):
    """`IF RAND:a == 0 / ELSEIF RAND:b == 0 / … / ELSE` の連鎖（上限 0 は ELSE）。該当なしは None。"""
    for n, *rest in table:
        if n == 0 or rand(n) == 0:
            return rest[0] if len(rest) == 1 else tuple(rest)
    return None


