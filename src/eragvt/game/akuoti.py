def self_call(ctx: Ctx, who: int = 0) -> str:
    """`口上/口上システム関係/SELF_CALL.ERB@SELF_CALL(0, 0, SELF_TARGET)`:31–60（オプション・伸ばし無し）。
    キャラ番号 0（省略）は TARGET。CSTR:4 が空なら SELF_CALL_LIST(CFLAG:8 / 5 % 20, CFLAG:8 % 5)。"""
    from .firstsetting import self_call_list

    st = ctx.state
    if who == 0:
        who = st.target
    c = st.charas[who]
    if c.cstr[4] != "":
        return c.cstr[4]
    v = c.cflag[8]
    if v < 0:
        raise NotImplementedError("SELF_CALL：CFLAG:8 が負")
    return self_call_list(div(v, 5) % 20, v % 5)


